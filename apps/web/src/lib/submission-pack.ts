/**
 * Convert a data URL to a Uint8Array for ZIP inclusion
 */
function dataUrlToUint8Array(dataUrl: string): Uint8Array {
  const parts = dataUrl.split(",");
  const base64 = parts[1] ?? "";
  const binary = atob(base64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
  }
  return bytes;
}

/**
 * Get file extension from data URL mime type
 */
function getExtensionFromDataUrl(dataUrl: string): string {
  const match = dataUrl.match(/data:image\/(\w+)/);
  if (match && match[1]) {
    const type = match[1];
    if (type === "jpeg") return "jpg";
    return type;
  }
  return "png";
}

export interface GenerateSubmissionPackOptions {
  result: RuleEvaluationResult;
  assets?: StoredAssets;
}

/**
 * Generate the complete submission pack ZIP in the browser
 */
export async function generateSubmissionPack(
  options: GenerateSubmissionPackOptions
): Promise<SubmissionPackResult> {
  const { result, assets } = options;
  const zip = new JSZip();

  const contents: SubmissionPackContents = {
    hasReport: true,
    copyPasteFiles: [],
    screenshots: [],
    hasFeatureGraphic: false,
    hasIcon: false,
    checklists: [],
  };

  // Add HTML report
  const htmlReport = generateHtmlReport(result);
  zip.file("reports/storepreflight.html", htmlReport);

  // Add copy-paste files
  const copyFiles = generateCopyPasteFiles(result.findings);
  for (const [filename, content] of copyFiles) {
    zip.file(`copy-paste/${filename}`, content);
    contents.copyPasteFiles.push(filename);
  }

  // Add checklists
  const checklistFiles = generateChecklists(result);
  for (const [filename, content] of checklistFiles) {
    zip.file(`checklists/${filename}`, content);
    contents.checklists.push(filename);
  }

  // Add assets if provided
  if (assets) {
    // Android screenshots
    if (assets.android.screenshots.length > 0) {
      assets.android.screenshots.forEach((dataUrl, index) => {
        const ext = getExtensionFromDataUrl(dataUrl);
        const filename = `screenshot_${index + 1}.${ext}`;
        zip.file(`assets/google-play/screenshots/${filename}`, dataUrlToUint8Array(dataUrl));
        contents.screenshots.push(`google-play/${filename}`);
      });
    }

    // Android feature graphic
    if (assets.android.feature) {
      const ext = getExtensionFromDataUrl(assets.android.feature);
      zip.file(`assets/google-play/feature-graphic.${ext}`, dataUrlToUint8Array(assets.android.feature));
      contents.hasFeatureGraphic = true;
    }

    // Android icon
    if (assets.android.icon) {
      const ext = getExtensionFromDataUrl(assets.android.icon);
      zip.file(`assets/google-play/icon-512.${ext}`, dataUrlToUint8Array(assets.android.icon));
      contents.hasIcon = true;
    }

    // iOS screenshots
    if (assets.ios.screenshots.length > 0) {
      assets.ios.screenshots.forEach((dataUrl, index) => {
        const ext = getExtensionFromDataUrl(dataUrl);
        const filename = `screenshot_${index + 1}.${ext}`;
        zip.file(`assets/app-store/screenshots/${filename}`, dataUrlToUint8Array(dataUrl));
        contents.screenshots.push(`app-store/${filename}`);
      });
    }

    // iOS icon
    if (assets.ios.icon) {
      const ext = getExtensionFromDataUrl(assets.ios.icon);
      zip.file(`assets/app-store/icon-1024.${ext}`, dataUrlToUint8Array(assets.ios.icon));
      if (!contents.hasIcon) contents.hasIcon = true;
    }
  }

  // Add a README
  const readme = `# StorePreflight Submission Pack

Generated: ${new Date().toLocaleString()}
App: ${result.appName} (${result.bundleId})
Platforms: ${result.platformTargets.join(", ")}

## Contents

### /reports
- storepreflight.html - Full HTML report with all findings

### /copy-paste
${contents.copyPasteFiles.length > 0 ? contents.copyPasteFiles.map((f) => `- ${f}`).join("\n") : "- (no copy-paste files generated)"}

### /checklists
${contents.checklists.length > 0 ? contents.checklists.map((f) => `- ${f}`).join("\n") : "- (no checklists generated)"}

### /assets
${contents.screenshots.length > 0 || contents.hasIcon || contents.hasFeatureGraphic ? "Screenshots and icons for store submission" : "- (no assets included)"}

## How to Use

1. Open the HTML report in your browser for a full overview
2. Use the copy-paste files when filling out store forms
3. Follow the platform checklists to ensure nothing is missed
4. Upload assets directly to App Store Connect / Google Play Console

---
Generated by StorePreflight - Know what Apple and Google will ask before you submit.
`;
  zip.file("README.md", readme);

  // Generate the ZIP blob
  const blob = await zip.generateAsync({ type: "blob" });
  const filename = createPackFilename(result.appName);

  return {
    appName: result.appName,
    generatedAt: new Date().toISOString(),
    blob,
    filename,
    contents,
  };
}
