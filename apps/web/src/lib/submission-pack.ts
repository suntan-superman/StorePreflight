/**
 * Browser-side Submission Pack Generator
 * Creates a ZIP file with all submission materials using JSZip
 */

import JSZip from "jszip";
import type { RuleEvaluationResult, GateFinding } from "./browser-scanner";

export interface SubmissionPackContents {
  hasReport: boolean;
  copyPasteFiles: string[];
  screenshots: string[];
  hasFeatureGraphic: boolean;
  hasIcon: boolean;
  checklists: string[];
}

export interface SubmissionPackResult {
  appName: string;
  generatedAt: string;
  blob: Blob;
  filename: string;
  contents: SubmissionPackContents;
}

export interface StoredAssets {
  ios: { screenshots: string[]; icon?: string };
  android: { screenshots: string[]; icon?: string; feature?: string };
}

/**
 * Sanitize a filename by removing invalid characters
 */
function sanitizeFilename(name: string): string {
  return name
    .replace(/[^a-zA-Z0-9_-]/g, "_")
    .replace(/_+/g, "_")
    .slice(0, 50);
}

/**
 * Format current date for filename (YYYYMMDD)
 */
function formatDateForFilename(): string {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, "0");
  const day = String(now.getDate()).padStart(2, "0");
  return `${year}${month}${day}`;
}

/**
 * Create a submission pack filename
 */
function createPackFilename(appName: string): string {
  const safeName = sanitizeFilename(appName);
  const date = formatDateForFilename();
  return `StorePreflight_SubmissionPack_${safeName}_${date}.zip`;
}

/**
 * Generate copy-paste text files from findings
 */
function generateCopyPasteFiles(findings: GateFinding[]): Map<string, string> {
  const files = new Map<string, string>();

  const appPurposes: string[] = [];
  const permissionJustifications: string[] = [];
  const reviewerNotes: string[] = [];
  const dataSafetyEntries: Record<string, string> = {};

  for (const finding of findings) {
    if (finding.copy.appPurpose) {
      appPurposes.push(`[${finding.id}]\n${finding.copy.appPurpose}`);
    }
    if (finding.copy.permissionJustification) {
      permissionJustifications.push(`[${finding.id}]\n${finding.copy.permissionJustification}`);
    }
    if (finding.copy.reviewerNotes) {
      reviewerNotes.push(`[${finding.id}]\n${finding.copy.reviewerNotes}`);
    }
    if (finding.copy.dataSafety) {
      dataSafetyEntries[finding.id] = finding.copy.dataSafety;
    }
  }

  if (appPurposes.length > 0) {
    files.set("google_app_purpose.txt", appPurposes.join("\n\n---\n\n"));
  }

  if (permissionJustifications.length > 0) {
    files.set("google_permission_justifications.txt", permissionJustifications.join("\n\n---\n\n"));
  }

  if (reviewerNotes.length > 0) {
    files.set("reviewer_notes.txt", reviewerNotes.join("\n\n---\n\n"));
  }

  if (Object.keys(dataSafetyEntries).length > 0) {
    files.set("data_safety.json", JSON.stringify(dataSafetyEntries, null, 2));
  }

  return files;
}

/**
 * Generate platform-specific checklists
 */
function generateChecklists(result: RuleEvaluationResult): Map<string, string> {
  const checklists = new Map<string, string>();

  const googleFindings = result.findings.filter(
    (f) => f.platform === "google" || f.platform === "both"
  );

  const appleFindings = result.findings.filter(
    (f) => f.platform === "apple" || f.platform === "both"
  );

  if (result.platformTargets.includes("android")) {
    const items = googleFindings.map((f) => {
      const checks: string[] = [];
      if (f.requires.video) checks.push("Upload YouTube demo video");
      if (f.requires.screenshots) checks.push("Prepare screenshots");
      if (f.requires.reviewerNotes) checks.push("Add reviewer notes");
      if (f.copy.permissionJustification) checks.push("Add permission justification");
      if (f.copy.dataSafety) checks.push("Complete Data Safety form");

      return checks.length > 0
        ? `## ${f.id}\n\n${checks.map((c) => `- [ ] ${c}`).join("\n")}`
        : null;
    }).filter(Boolean);

    if (items.length > 0) {
      checklists.set(
        "google-play.md",
        `# Google Play Console Checklist\n\nGenerated by StorePreflight on ${new Date().toLocaleDateString()}\n\n${items.join("\n\n")}`
      );
    }
  }

  if (result.platformTargets.includes("ios")) {
    const items = appleFindings.map((f) => {
      const checks: string[] = [];
      if (f.requires.screenshots) checks.push("Prepare screenshots");
      if (f.requires.reviewerNotes) checks.push("Add App Review notes");
      if (f.copy.permissionJustification) checks.push("Add usage description");

      return checks.length > 0
        ? `## ${f.id}\n\n${checks.map((c) => `- [ ] ${c}`).join("\n")}`
        : null;
    }).filter(Boolean);

    if (items.length > 0) {
      checklists.set(
        "app-store.md",
        `# App Store Connect Checklist\n\nGenerated by StorePreflight on ${new Date().toLocaleDateString()}\n\n${items.join("\n\n")}`
      );
    }
  }

  return checklists;
}

